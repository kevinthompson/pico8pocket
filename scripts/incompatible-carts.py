#!/usr/bin/env python3
"""Generate the compiled incompatibility list and its README table."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '<!-- incompatible-carts:begin -->'
END = '<!-- incompatible-carts:end -->'


def load_entries(path):
    entries = json.loads(path.read_text())
    if not isinstance(entries, list):
        raise ValueError('registry must be a list')
    hashes = set()
    fields = {'title', 'filename', 'content_hash', 'reason', 'workaround', 'evidence', 'issue'}
    for entry in entries:
        if not isinstance(entry, dict) or set(entry) != fields:
            raise ValueError('each entry needs exactly: ' + ', '.join(sorted(fields)))
        for key, value in entry.items():
            if not isinstance(value, str) or not value or not value.isascii() or any(ord(c) < 32 for c in value):
                raise ValueError(f'invalid {key}: expected nonempty printable ASCII')
        fingerprint = entry['content_hash']
        if not re.fullmatch(r'[0-9a-f]{32}', fingerprint) or fingerprint in hashes:
            raise ValueError('content hashes must be unique lowercase 16-byte hex values')
        hashes.add(fingerprint)
        message = '{title} incompatible.\n{reason}\n{workaround}'.format(**entry)
        if len(message) >= 256:
            raise ValueError(f"on-screen explanation too long: {entry['title']}")
        if not entry['issue'].startswith('https://'):
            raise ValueError('issue must be an HTTPS URL')
    return entries


def compiled_entries(entries):
    lines = ['/* Generated by scripts/incompatible-carts.py. Edit compatibility/incompatible-carts.json. */']
    for entry in entries:
        fingerprint = ', '.join(f'0x{entry["content_hash"][i:i+2]}' for i in range(0, 32, 2))
        lines.append('    {{' + fingerprint + '}, ' + ', '.join(json.dumps(entry[key]) for key in ('title', 'reason', 'workaround')) + '},')
    return '\n'.join(lines) + '\n'


def markdown_table(entries):
    def cell(value):
        return value.replace('|', '&#124;').replace('`', '&#96;')
    lines = ['| Cartridge revision | Why it is blocked | Workaround / support |', '|---|---|---|']
    for entry in entries:
        lines.append(f'| {cell(entry["title"])} (`{cell(entry["filename"])}`) | {cell(entry["reason"])} | {cell(entry["workaround"])} [Issue]({entry["issue"]}) |')
    return '\n'.join(lines)


def update(root, check):
    entries = load_entries(root / 'compatibility/incompatible-carts.json')
    readme_path = root / 'README.md'
    readme = readme_path.read_text()
    if readme.count(BEGIN) != 1 or readme.count(END) != 1 or readme.index(BEGIN) >= readme.index(END):
        raise ValueError('README needs exactly one ordered incompatibility marker pair')
    start = readme.index(BEGIN) + len(BEGIN)
    end = readme.index(END)
    outputs = {
        root / 'include/p8p/incompatible_carts.inc': compiled_entries(entries),
        readme_path: readme[:start] + '\n' + markdown_table(entries) + '\n' + readme[end:],
    }
    stale = []
    for path, content in outputs.items():
        if path.exists() and path.read_text() == content:
            continue
        stale.append(str(path.relative_to(root)))
        if not check:
            path.write_text(content)
    if stale and check:
        print('Out of date: ' + ', '.join(stale) + '; run python3 scripts/incompatible-carts.py', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated C or README differs')
    args = parser.parse_args()
    try:
        sys.exit(update(ROOT, args.check))
    except (ValueError, OSError) as error:
        parser.exit(2, f'{error}\n')
