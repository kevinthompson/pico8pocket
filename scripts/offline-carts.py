#!/usr/bin/env python3
"""Keep the core's offline-collection requirements aligned with the installer."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
FEATURES = {'arcade': 'P8P_CART_FEATURE_OFFLINE_ARCADE',
            'sorcerer': 'P8P_CART_FEATURE_OFFLINE_SORCERER'}


def generate(root, check):
    data = json.loads((root / 'compatibility/offline-carts.json').read_text())
    if not isinstance(data, dict) or set(data) != {'version', 'carts'} or data['version'] != 1:
        raise ValueError('expected offline catalog version 1')
    if not isinstance(data['carts'], list) or not 1 <= len(data['carts']) <= 256:
        raise ValueError('catalog needs 1..256 cartridges')
    ids = set()
    groups = set()
    lines = ['/* Generated by scripts/offline-carts.py from compatibility/offline-carts.json. */']
    for entry in data['carts']:
        if not isinstance(entry, dict) or set(entry) != {'id', 'name', 'collection'}:
            raise ValueError('each cart needs id, name and collection')
        key, name, group = entry['id'], entry['name'], entry['collection']
        if not isinstance(key, str) or not re.fullmatch(r'[a-z0-9_-]{1,47}', key) or key in ids:
            raise ValueError('IDs must be unique lowercase ASCII identifiers of 1..47 characters')
        if not isinstance(group, str) or group not in FEATURES:
            raise ValueError('unknown collection')
        if not isinstance(name, str) or not name or not name.isascii() or any(ord(c) < 32 for c in name):
            raise ValueError('cart names must be printable ASCII')
        ids.add(key)
        groups.add(group)
        lines.append('    {' + json.dumps(key) + ', ' + FEATURES[group] + '},')
    if groups != set(FEATURES):
        raise ValueError('both Arcade and Sorcerer collections must be represented')
    result = '\n'.join(lines) + '\n'
    target = root / 'include/p8p/bbs_catalog.inc'
    if not target.exists() or target.read_text() != result:
        if check:
            print('Core BBS catalog is out of date; run python3 scripts/offline-carts.py', file=sys.stderr)
            return 1
        target.write_text(result)
    return 0


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args()
    try:
        sys.exit(generate(args.root, args.check))
    except (ValueError, OSError) as error:
        parser.exit(2, f'{error}\n')
